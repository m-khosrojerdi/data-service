package com.mapnadigital.insights.data.model.entity;

import jakarta.persistence.*;
import jakarta.validation.constraints.Pattern;
import lombok.AllArgsConstructor;
import lombok.Getter;
import lombok.NoArgsConstructor;
import lombok.Setter;
import org.hibernate.annotations.ColumnDefault;
import org.hibernate.annotations.DialectOverride;
import org.hibernate.dialect.PostgreSQLDialect;

import java.io.Serializable;

/**
 * Baseline value of a topic of a device.
 * <p>
 * The entity is owned by this module and maps the table {@code data_history.device_baseline_values}. The topic tree
 * is a relation of the same module; the device belongs to {@code device-service}, so it is only referenced by its
 * identifier ({@code deviceId}) and the column name is kept so the schema does not change.
 * <p>
 * Mapping notes:
 * <ul>
 *     <li>the physical names are declared explicitly in snake case, so the generated schema does not depend on the
 *     naming strategy of the runtime;</li>
 *     <li>{@code (device_id, topic_tree_id, interval)} is unique because it is the business key used by
 *     {@code BaselineRepository.findByDeviceIdAndTopicTreeIdAndInterval};</li>
 *     <li>both foreign key columns are indexed because they are the filters of the baseline look-ups;</li>
 *     <li>the identifier is generated by the {@code data_history.device_baseline_values_id_seq} sequence with an
 *     allocation size of one, and the PostgreSQL column default points at the same sequence, so a row inserted by
 *     hand without {@code id} also receives the next sequence value.</li>
 * </ul>
 *
 * @author Mohammad Khosrojerdi khosrojerdi.mohammad@gmail.com
 * @since 1.0
 */
@Getter
@Setter
@AllArgsConstructor
@NoArgsConstructor
@Entity
@Table(
        name = "device_baseline_values",
        schema = "data_history",
        uniqueConstraints = @UniqueConstraint(name = "uk_device_baseline_values_device_topic_interval",
                columnNames = {"device_id", "topic_tree_id", "interval"}),
        indexes = {
                @Index(name = "idx_device_baseline_values_device", columnList = "device_id"),
                @Index(name = "idx_device_baseline_values_topic_tree", columnList = "topic_tree_id")
        }
)
public class Baseline implements Serializable {

    @Id
    @GeneratedValue(strategy = GenerationType.SEQUENCE, generator = "device_baseline_values_seq")
    @SequenceGenerator(name = "device_baseline_values_seq", sequenceName = "device_baseline_values_id_seq",
            schema = "data_history", initialValue = 1, allocationSize = 1)
    @DialectOverride.ColumnDefault(dialect = PostgreSQLDialect.class,
            override = @ColumnDefault("nextval('data_history.device_baseline_values_id_seq')"))
    @Column(name = "id", nullable = false, updatable = false)
    private Long id;

    /**
     * Identifier of the device of {@code device-service}; the association was replaced by the identifier so that
     * the module keeps the column (and therefore the schema) and does not depend on the device domain.
     */
    @Column(name = "device_id", nullable = false)
    private Long deviceId;

    @ManyToOne(fetch = FetchType.LAZY)
    @JoinColumn(name = "topic_tree_id", nullable = false,
            foreignKey = @ForeignKey(name = "fk_device_baseline_values_topic_tree"))
    private TopicTree topicTree;

    @Pattern(regexp = "^(?=.+)(?:(?:1\\s+year|[2-9]\\d*\\s+years)\\s*)?(?:(?:1\\s+month|[2-9]\\d*\\s+months)\\s*)?(?:(?:1\\s+day|[2-9]\\d*\\s+days)\\s*)?(?:(?:1\\s+hour|[2-9]\\d*\\s+hours)\\s*)?(?:(?:1\\s+min|[2-9]\\d*\\s+mins)\\s*)?(?:(?:1\\s+second|[2-9]\\d*\\s+seconds))?$",
            message = "Invalid interval format. Example: '1 day 2 minutes 3 seconds'")
    @Column(name = "interval")
    private String interval;

    @Column(name = "value", nullable = false)
    private Double value;

}
