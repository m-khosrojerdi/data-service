package com.mapnadigital.insights.data.model.entity;

import jakarta.persistence.*;
import lombok.*;
import org.hibernate.annotations.ColumnDefault;
import org.hibernate.annotations.DialectOverride;
import org.hibernate.dialect.PostgreSQLDialect;

import java.io.Serializable;
import java.sql.Timestamp;

/**
 * Raw value of a topic.
 * <p>
 * The entity is owned by this module and maps the table {@code data_history.data}. It has no relation to another
 * module.
 * <p>
 * Mapping notes:
 * <ul>
 *     <li>the table and the columns are declared explicitly in snake case, so the generated schema does not depend
 *     on the naming strategy of the runtime;</li>
 *     <li>{@code topic} and {@code date_time} are indexed because every read of the telemetry is filtered on the
 *     topic and on a time range;</li>
 *     <li>the identifier is generated by the {@code data_history.data_id_seq} sequence with an allocation size of
 *     one, and the PostgreSQL column default points at the same sequence, so a row inserted by hand without
 *     {@code id} also receives the next sequence value.</li>
 * </ul>
 *
 * @author Mohammad Khosrojerdi khosrojerdi.mohammad@gmail.com
 * @since 1.0
 */
@Getter
@Setter
@Builder
@AllArgsConstructor
@NoArgsConstructor
@Entity
@Table(
        name = "data",
        schema = "data_history",
        indexes = {
                @Index(name = "idx_data_topic", columnList = "topic"),
                @Index(name = "idx_data_date_time", columnList = "date_time")
        }
)
public class Data implements Serializable {

    @Id
    @GeneratedValue(strategy = GenerationType.SEQUENCE, generator = "data_seq")
    @SequenceGenerator(name = "data_seq", sequenceName = "data_id_seq", schema = "data_history",
            initialValue = 1, allocationSize = 1)
    @DialectOverride.ColumnDefault(dialect = PostgreSQLDialect.class,
            override = @ColumnDefault("nextval('data_history.data_id_seq')"))
    @Column(name = "id", nullable = false, updatable = false)
    private Long id;

    @Column(name = "value")
    private String value;

    @Column(name = "date_time")
    private Timestamp dateTime;

    @Column(name = "topic")
    private String topic;

}
