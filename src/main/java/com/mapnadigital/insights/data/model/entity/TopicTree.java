package com.mapnadigital.insights.data.model.entity;

import jakarta.persistence.*;
import lombok.AllArgsConstructor;
import lombok.Getter;
import lombok.NoArgsConstructor;
import lombok.Setter;
import org.hibernate.annotations.ColumnDefault;
import org.hibernate.annotations.DialectOverride;
import org.hibernate.dialect.PostgreSQLDialect;

import java.io.Serializable;
import java.util.Date;

/**
 * Node of the topic tree of the devices.
 * <p>
 * The entity is owned by this module and maps the table {@code data_history.topic_tree}. The parent is a relation of
 * the same module, so it stays a {@code @ManyToOne}.
 * <p>
 * Mapping notes:
 * <ul>
 *     <li>the physical names are declared explicitly in snake case, so the generated schema does not depend on the
 *     naming strategy of the runtime and stays aligned with the native statement of
 *     {@code TopicTreeRepository.findLeafTopics} ({@code data_history.topic_tree}, {@code parent_id});</li>
 *     <li>{@code (topic, parent_id)} is unique: a topic name is only unique inside its parent, which is what the
 *     tree assembly of {@code TopicTreeService} relies on;</li>
 *     <li>{@code parent_id} and {@code path} are indexed because every read of the tree filters on them;</li>
 *     <li>the identifier is generated by the {@code data_history.topic_tree_id_seq} sequence. The sequence is
 *     declared with an allocation size of one, so Hibernate calls {@code nextval} for every insert and never
 *     reserves a block of identifiers that a manual SQL insert could collide with. The PostgreSQL column default is
 *     declared as a dialect override and points at the same sequence, so a row inserted by hand without
 *     {@code id} also receives the next sequence value;</li>
 *     <li>{@code log_time} is a {@code timestamp} column, hence the {@link java.util.Date} mapping.</li>
 * </ul>
 *
 * @author Mohammad Khosrojerdi khosrojerdi.mohammad@gmail.com
 * @since 1.0
 */
@Getter
@Setter
@Entity
@NoArgsConstructor
@AllArgsConstructor
@Table(
        name = "topic_tree",
        schema = "data_history",
        uniqueConstraints = @UniqueConstraint(name = "uk_topic_tree_topic_parent",
                columnNames = {"topic", "parent_id"}),
        indexes = {
                @Index(name = "idx_topic_tree_parent", columnList = "parent_id"),
                @Index(name = "idx_topic_tree_path", columnList = "path")
        }
)
public class TopicTree implements Serializable {

    public TopicTree(TopicTree topicTree, Boolean hasChildren) {
        this.id = topicTree.getId();
        this.topic = topicTree.getTopic();
        this.parent = topicTree.getParent();
        this.isProperty = topicTree.getIsProperty();
        this.level = topicTree.getLevel();
        this.description = topicTree.getDescription();
        this.logTime = topicTree.getLogTime();
        this.path = topicTree.getPath();
        this.priority = topicTree.getPriority();
        this.isVisible = topicTree.getIsVisible();
        this.unit = topicTree.getUnit();
        this.hasChildren = hasChildren;
    }

    @Id
    @GeneratedValue(strategy = GenerationType.SEQUENCE, generator = "topic_tree_seq")
    @SequenceGenerator(name = "topic_tree_seq", sequenceName = "topic_tree_id_seq", schema = "data_history",
            initialValue = 1, allocationSize = 1)
    @DialectOverride.ColumnDefault(dialect = PostgreSQLDialect.class,
            override = @ColumnDefault("nextval('data_history.topic_tree_id_seq')"))
    @Column(name = "id", nullable = false, updatable = false)
    private Long id;

    @Column(name = "topic", nullable = false)
    private String topic;

    @ManyToOne(fetch = FetchType.EAGER)
    @JoinColumn(name = "parent_id", foreignKey = @ForeignKey(name = "fk_topic_tree_parent"))
    private TopicTree parent;

    @Column(name = "is_property")
    private Integer isProperty;

    @Column(name = "level")
    private Integer level;

    @Column(name = "description")
    private String description;

    @Column(name = "log_time", nullable = false)
    private Date logTime;

    @Column(name = "path")
    private String path;

    @Column(name = "priority")
    private Integer priority;

    @Column(name = "is_visible")
    private Boolean isVisible;

    @Column(name = "unit")
    private String unit;

    @Transient
    private Boolean hasChildren;
}
